namespace WebShelf.Classes.Security;

/// <summary>
/// Идентификаторы ролей WebShelf. Значение элемента совпадает с индексом
/// старшинства (<see cref="AppRole.SeniorityIndex"/>): 0 — старшая роль
/// (Администратор), 9 — младшая (Гость). Состав ролей фиксирован и задаётся
/// каталогом <see cref="RoleCatalog"/>; перечисление используется как тип
/// идентификатора роли и в проверках доступа
/// (<see cref="ClaimsPrincipalExtensions.IsInRole"/> и
/// <see cref="ClaimsPrincipalExtensions.IsAtLeast"/>).
/// Гость назначается автоматически при отсутствии ролевых групп и
/// AD-группы не имеет.
/// </summary>
internal enum AppRoleId : byte
{
    /// <summary>
    /// 0) Администратор — максимальный уровень доступа.
    /// В системе в каждый момент времени должен быть минимум один администратор.
    /// </summary>
    Administrator = 0,

    /// <summary>
    /// 1) Директор — права менеджера и управление ролями и разделами всех пользователей.
    /// </summary>
    Director = 1,

    /// <summary>
    /// 2) BIM-менеджер — права менеджера и специальные функции BIM-менеджера.
    /// </summary>
    BimManager = 2,

    /// <summary>
    /// 3) Менеджер — доступ к документации всех объектов.
    /// </summary>
    Manager = 3,

    /// <summary>
    /// 4) ГИП — доступ к документации всех объектов.
    /// </summary>
    Gip = 4,

    /// <summary>
    /// 5) Руководитель группы — доступ к документации определённых разделов.
    /// </summary>
    GroupLeader = 5,

    /// <summary>
    /// 6) Исполнитель — доступ к документации определённых разделов, всех объектов.
    /// </summary>
    Executor = 6,

    /// <summary>
    /// 7) Внешний исполнитель — доступ к документации назначенных объектов.
    /// </summary>
    ExternalExecutor = 7,

    /// <summary>
    /// 8) Заказчик — просмотр и выгрузка выданной документации.
    /// </summary>
    Customer = 8,

    /// <summary>
    /// 9) Гость — пользователь без единой ролевой группы; fallback при
    /// отсутствии совпадений. Под Гостя группа в AD не создаётся.
    /// </summary>
    Guest = 9
}
