namespace WebShelf.Classes.Service;

/// <summary>
/// Решение окна «Активация разрешения» по результату проверки пермита:
/// какое сообщение показать пользователю и включать ли блокировку
/// с обратным отсчётом. Чистая логика без UI и таймеров — страница
/// применяет решение к элементам окна (сообщения <c>ws-message</c>,
/// блокировка поля и кнопки «Продолжить»).
/// </summary>
/// <param name="ErrorMessage">Сообщение об ошибке для пользователя;
/// <see langword="null"/> — сообщения нет.</param>
/// <param name="StartLockout"><see langword="true"/> — включить блокировку
/// с обратным отсчётом (после первой неудачной попытки).</param>
/// <remarks>
/// Блокировка включается только за неверный или исчерпанный пермит —
/// уже после первой неудачной попытки (поведение как у блокировки формы
/// входа при неверной паре логин/пароль, но с первой попытки, а не с пятой).
/// Красное сообщение о неверном пермите не показывается: таймер включается
/// сразу, и оранжевый блок с обратным отсчётом сам объясняет причину —
/// оформление как на форме входа. Пустой ввод и ошибки сервера не списываются
/// на пользователя: сообщение без блокировки, повторная попытка возможна сразу.
/// Тексты сообщений вынесены в константы — страница показывает их без изменений.
/// </remarks>
internal sealed record PermitCheckOutcome(string? ErrorMessage, bool StartLockout)
{
    /// <summary>Сообщение о пустом вводе (без блокировки).</summary>
    internal const string EmptyPermitMessage = "Введите ключ разрешения.";

    /// <summary>Сообщение об ошибке сервера при проверке (без блокировки).</summary>
    internal const string ServerErrorMessage = "Ошибка сервера при проверке пермита. Повторите попытку.";

    /// <summary>
    /// Строит решение по результату проверки пермита в БД: пригодный пермит —
    /// без сообщения и блокировки; неверный или исчерпанный — блокировка
    /// с обратным отсчётом уже после первой неудачной попытки, без красного
    /// сообщения (таймер включается сразу и сам объясняет причину — оформление
    /// как на форме входа). Длительность блокировки определяет серверный
    /// PermitActivationGuard (эскалация с удвоением до 15 минут) — решение
    /// только сообщает, что блокировать.
    /// </summary>
    /// <param name="result">Результат проверки пермита.</param>
    /// <returns>Решение; никогда <see langword="null"/>.</returns>
    internal static PermitCheckOutcome FromResult(RegistrationPermitCheckResult result)
        => result.IsUsable
            ? new PermitCheckOutcome(null, false)
            : new PermitCheckOutcome(null, true);

    /// <summary>
    /// Решение для пустого ввода: сообщение без блокировки и без обращения
    /// к БД — как пустая пара логин/пароль на форме входа (атрибуты
    /// <c>required</c> не пропускают пустую отправку до проверки).
    /// </summary>
    /// <returns>Решение; никогда <see langword="null"/>.</returns>
    internal static PermitCheckOutcome FromEmptyInput()
        => new(EmptyPermitMessage, false);

    /// <summary>
    /// Решение для ошибки сервера при проверке (БД недоступна и т.п.):
    /// сообщение без блокировки — ошибка не списывается на пользователя,
    /// повторная попытка возможна сразу.
    /// </summary>
    /// <returns>Решение; никогда <see langword="null"/>.</returns>
    internal static PermitCheckOutcome FromServerError()
        => new(ServerErrorMessage, false);
}
