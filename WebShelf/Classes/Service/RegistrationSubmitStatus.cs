namespace WebShelf.Classes.Service;

/// <summary>
/// Статус подачи заявки на регистрацию в таблицу
/// <c>webshelf.registration_requests</c> (см. <see cref="RegistrationSubmitResult"/>).
/// </summary>
internal enum RegistrationSubmitStatus
{
    /// <summary>
    /// Заявка записана в таблицу (идентификатор УЗ AD оставлен NULL — заявка
    /// ожидает решения администратора), счётчик пермита уменьшен на 1.
    /// </summary>
    Success,

    /// <summary>
    /// Пермит не найден или его счётчик равен нулю (исчерпан между проверкой
    /// и подачей — например, регистрацию по нему выполнил другой кандидат).
    /// Заявка не записана, счётчик не менялся.
    /// </summary>
    PermitNotUsable,

    /// <summary>
    /// Заявка с таким адресом электронной почты уже подана. Новая заявка
    /// не записана, счётчик не менялся.
    /// </summary>
    EmailTaken,

    /// <summary>
    /// Заявка с таким номером телефона уже подана. Новая заявка не записана,
    /// счётчик не менялся.
    /// </summary>
    PhoneTaken,

    /// <summary>
    /// Ошибка сервера при подаче заявки (БД недоступна, сбой записи и т.п.).
    /// Заявка не записана, счётчик не менялся.
    /// </summary>
    ServerError
}
